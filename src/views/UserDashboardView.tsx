import React from 'react';
import { Radio, Clock, Car, Info, AlertTriangle } from 'lucide-react';
import { useStationData } from '../context/StationDataContext';
import { DataBadge } from '../components/common/DataBadge';
import { ReadingTile } from '../components/common/ReadingTile';
import { Notice } from '../components/common/Notice';
import { ReadingKind } from '../types/station';

export const UserDashboardView: React.FC = () => {
  const { state, isStale, secondsSinceLastHeartbeat } = useStationData();
  const isDemo = state.dataSourceMode === 'demo';
  const r = state.latestReadings;

  // Labelling rule: demo values are 'simulated'; stale overrides; live values would be 'live'.
  const baseKind: ReadingKind = isStale ? 'stale' : isDemo ? 'simulated' : 'live';
  const fmt = (v: number | null, digits: number) => (v === null ? null : v.toFixed(digits));

  return (
    <div className="space-y-12">
      <div className="flex flex-col sm:flex-row sm:items-end justify-between gap-4 pb-8 border-b border-[var(--color-border)]">
        <div className="space-y-2">
          <h1 className="h2-fluid text-[var(--color-text)]">User Charging Dashboard</h1>
          <p className="text-sm text-[var(--color-text-secondary)] max-w-xl">
            RFID access feedback, session state and electrical readings for {state.stationName}.
          </p>
        </div>
        <DataBadge kind={isDemo ? 'simulated' : 'unavailable'} label={isDemo ? 'Simulated demo data' : 'No live data source'} />
      </div>

      {isDemo ? (
        <Notice variant="simulated" icon={<Info className="w-5 h-5" />} title="You are viewing simulated demo data">
          Values below are generated by the interface for demonstration. They do not come from hardware.
        </Notice>
      ) : (
        <Notice variant="warning" icon={<AlertTriangle className="w-5 h-5" />} title="Live data is unavailable">
          {state.errorMessage}
        </Notice>
      )}

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-8">
        <div className="lg:col-span-5 space-y-8">
          <div className="card-premium space-y-6">
            <div className="flex items-center justify-between">
              <span className="text-xs font-bold text-[var(--color-text-muted)] uppercase tracking-wider">RFID access</span>
              <DataBadge kind={isDemo ? 'simulated' : 'unavailable'} />
            </div>
            <div className="p-8 rounded-xl bg-[var(--color-surface-elevated)] border border-dashed border-[var(--color-border)] flex flex-col items-center text-center space-y-3">
              <div className="w-14 h-14 rounded-2xl bg-[var(--primitive-teal)]/10 text-[var(--color-primary)] flex items-center justify-center">
                <Radio className="w-7 h-7" />
              </div>
              <span className="text-sm font-semibold text-[var(--color-text)]">
                {isDemo ? 'Simulated reader: no card input is processed' : 'Reader status unavailable'}
              </span>
              <span className="text-xs text-[var(--color-text-muted)]">
                Access results will appear here only when the system reports them.
              </span>
            </div>
            <p className="text-xs leading-relaxed text-[var(--color-text-muted)]">
              RFID identifies a card or tag. It does not measure battery level.
            </p>
          </div>

          <div className="card-premium space-y-4">
            <div className="flex items-center justify-between">
              <span className="text-xs font-bold text-[var(--color-text-muted)] uppercase tracking-wider">Session</span>
              <Clock className="w-4 h-4 text-[var(--color-text-muted)]" />
            </div>
            <div className="font-tabular text-3xl font-semibold text-center py-5 rounded-xl bg-[var(--color-surface-elevated)] border border-[var(--color-border)] text-[var(--color-text-muted)]">
              —
            </div>
            <div className="flex items-center justify-between gap-3">
              <p className="text-xs text-[var(--color-text-muted)]">No session reported. Duration starts only when one is.</p>
              <DataBadge kind="unavailable" />
            </div>
          </div>
        </div>

        <div className="lg:col-span-7 space-y-8">
          <div className="card-premium space-y-6">
            <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-2">
              <div>
                <h3 className="text-base font-bold text-[var(--color-text)]">Electrical readings</h3>
                <p className="text-xs text-[var(--color-text-secondary)] mt-1">
                  {isDemo
                    ? `Simulated update ${secondsSinceLastHeartbeat ?? 0}s ago`
                    : 'No readings received'}
                </p>
              </div>
              {isStale && <DataBadge kind="stale" label="Stale: not current" />}
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
              <ReadingTile label="Voltage" value={fmt(r.voltage, 2)} unit="V" kind={baseKind} />
              <ReadingTile label="Current" value={fmt(r.current, 0)} unit="mA" kind={baseKind} />
              <ReadingTile
                label="Power"
                value={fmt(r.power, 2)}
                unit="W"
                kind={isStale ? 'stale' : isDemo ? 'simulated' : 'derived'}
                note="Derived: P = V × I"
              />
            </div>

            <div className="card-flat flex items-center justify-between gap-4">
              <div className="flex items-center gap-3">
                <Car className="w-5 h-5 text-[var(--color-text-muted)] flex-shrink-0" />
                <div>
                  <span className="text-sm font-semibold text-[var(--color-text)] block">Vehicle presence</span>
                  <span className="text-xs text-[var(--color-text-muted)]">
                    {r.vehicleDetected === null
                      ? 'Presence sensor not integrated'
                      : r.vehicleDetected ? 'Detected' : 'Not detected'}
                  </span>
                </div>
              </div>
              <DataBadge kind={r.vehicleDetected === null ? 'unavailable' : baseKind} />
            </div>
          </div>

          <Notice title="Not shown on purpose">
            Battery level, energy delivered, charging completion and solar contribution are not displayed, because no verified measurement method exists for them yet.
          </Notice>
        </div>
      </div>
    </div>
  );
};
