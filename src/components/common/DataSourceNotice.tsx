import React from 'react';
import { Info, AlertTriangle } from 'lucide-react';
import { Notice } from './Notice';
import { useStationData } from '../../context/StationDataContext';

/** Banner explaining what the current data source means. */
export const DataSourceNotice: React.FC = () => {
  const { state } = useStationData();
  return state.dataSourceMode === 'demo' ? (
    <Notice variant="simulated" icon={<Info className="w-5 h-5" />} title="You are viewing simulated demo data">
      Values are generated by the interface for demonstration. They do not come from hardware.
    </Notice>
  ) : state.connectionStatus === 'connected' ? (
    <Notice icon={<Info className="w-5 h-5" />} title="Live data from the station">
      Readings come from SolarSmart Base 01 through the backend. Power is derived (P = V × I).
    </Notice>
  ) : state.connectionStatus === 'stale' ? (
    <Notice variant="warning" icon={<AlertTriangle className="w-5 h-5" />} title="Live data is stale">
      The station has not sent an update recently, so the values below may not be current.
    </Notice>
  ) : (
    <Notice variant="warning" icon={<AlertTriangle className="w-5 h-5" />} title="Live data is unavailable">
      {state.errorMessage}
    </Notice>
  );
};
